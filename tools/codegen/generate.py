#!/usr/bin/env python3
"""Generates typed backend entities/repositories/controllers, Flyway baseline DDL,
the resource catalog, OpenAPI contract and the web registry from model.py.

Usage:  python3 tools/codegen/generate.py
"""
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
sys.path.insert(0, HERE)
import model  # noqa: E402

JAVA_ROOT = os.path.join(ROOT, "backend/src/main/java/com/opesware/maintain")
PKG = "com.opesware.maintain"
HEADER = "// GENERATED by tools/codegen/generate.py from tools/codegen/model.py — do not edit by hand.\n"


def parse_field(spec):
    name, rest = spec.split(":", 1)
    m = re.match(r"^([a-z]+)(\(([^)]*)\))?([!*~#^]*)$", rest)
    if not m:
        raise ValueError("bad field " + spec)
    ftype, _, arg, flags = m.groups()
    f = dict(name=name, type=ftype, required="!" in flags, list="*" in flags, managed="~" in flags,
             hidden="#" in flags, computed="^" in flags, options=[], ref=None)
    if ftype == "enum":
        f["options"] = arg.split("|")
    if ftype == "ref":
        f["ref"] = arg
    return f


def label_of(name):
    n = name[:-2] if name.endswith("Id") and len(name) > 2 else name
    words = re.sub(r"([A-Z])", r" \1", n).split()
    out = " ".join(w if w.isupper() and len(w) > 1 else w.capitalize() for w in words)
    return out.replace("Sla ", "SLA ").replace("Pm ", "PM ").replace("Mfa", "MFA").replace("Vin", "VIN") \
        .replace("Sha256", "SHA-256").replace("Url", "URL")


def snake(name):
    return re.sub(r"([A-Z])", r"_\1", name).lower().lstrip("_")


JAVA_TYPES = {"str": "String", "text": "String", "enum": "String", "int": "Integer", "dec": "BigDecimal",
              "money": "BigDecimal", "bool": "Boolean", "date": "LocalDate", "datetime": "Instant", "ref": "UUID"}
SQL_TYPES = {"str": "varchar(255)", "text": "varchar(8000)", "enum": "varchar(64)", "int": "integer",
             "dec": "numeric(19,4)", "money": "numeric(19,4)", "bool": "boolean", "date": "date",
             "datetime": "timestamp with time zone", "ref": "uuid"}

resources = []
for r in model.R:
    r = dict(r)
    r["fields"] = [parse_field(s) for s in r["fields"]]
    for f in r["fields"]:
        f["label"] = label_of(f["name"])
        f["guarded"] = f["name"] in r["guarded"]
    r["table"] = snake(r["entity"]) if r["entity"] != "AppUser" else "app_user"
    if r["prefix"] and not any(f["name"] == "number" for f in r["fields"]):
        r["fields"].insert(0, dict(name="number", type="str", required=False, list=True, managed=True, hidden=False,
                                   computed=False, options=[], ref=None, label="Number", guarded=False))
    writers = r["writers"] if r["writers"] is not None else model.CONTEXT_WRITERS[r["context"]]
    r["writerRoles"] = sorted(set(["ADMIN"] + writers))
    r["display"] = r["display"] or "name"
    resources.append(r)

by_path = {r["path"]: r for r in resources}
for r in resources:
    for f in r["fields"]:
        if f["ref"] and f["ref"] not in by_path:
            raise SystemExit(f"{r['path']}.{f['name']} references unknown resource {f['ref']}")


def write(path, content):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as fh:
        fh.write(content)


def jstr(s):
    return json.dumps(s)


# ------------------------------------------------------------------ Java
for r in resources:
    ctx = r["context"]
    ent = r["entity"]
    imports = {"jakarta.persistence.Entity", "jakarta.persistence.Table",
               f"{PKG}.platform.domain.TenantEntity"}
    body = []
    for f in r["fields"]:
        jt = JAVA_TYPES[f["type"]]
        if jt == "BigDecimal":
            imports.add("java.math.BigDecimal")
        if jt == "LocalDate":
            imports.add("java.time.LocalDate")
        if jt == "Instant":
            imports.add("java.time.Instant")
        if jt == "UUID":
            imports.add("java.util.UUID")
        ann = ""
        if f["computed"]:
            imports.add("jakarta.persistence.Transient")
            ann = "    @Transient\n"
        elif f["type"] == "text":
            imports.add("jakarta.persistence.Column")
            ann = "    @Column(length = 8000)\n"
        body.append(f"{ann}    public {jt} {f['name']};\n")
    imp = "".join(f"import {i};\n" for i in sorted(imports))
    src = (f"{HEADER}package {PKG}.{ctx}.domain;\n\n{imp}\n"
           f"/** {r['singular']} — {r['desc']} ({r['module']}) */\n"
           f"@Entity\n@Table(name = \"{r['table']}\")\npublic class {ent} extends TenantEntity {{\n\n"
           + "\n".join(body) + "}\n")
    write(f"{JAVA_ROOT}/{ctx}/domain/{ent}.java", src)

    finders = "".join(f"    List<{ent}> findBy{f['name'][0].upper() + f['name'][1:]}(UUID value);\n\n"
                      for f in r["fields"] if f["ref"] and not f["computed"])
    finders += f"    List<{ent}> findByTenantId(UUID tenantId);\n"
    repo = (f"{HEADER}package {PKG}.{ctx}.infrastructure;\n\n"
            f"import {PKG}.{ctx}.domain.{ent};\nimport {PKG}.platform.infrastructure.TenantRepository;\n"
            f"import java.util.List;\nimport java.util.UUID;\n\n"
            f"public interface {ent}Repository extends TenantRepository<{ent}> {{\n\n{finders}}}\n")
    write(f"{JAVA_ROOT}/{ctx}/infrastructure/{ent}Repository.java", repo)

    base = "ReadController" if r["readonly"] else "CrudController"
    ctl = (f"{HEADER}package {PKG}.{ctx}.api;\n\n"
           f"import {PKG}.platform.api.{base};\nimport {PKG}.platform.application.CrudService;\n"
           f"import org.springframework.web.bind.annotation.RequestMapping;\n"
           f"import org.springframework.web.bind.annotation.RestController;\n\n"
           f"/** REST resource for {r['label']} ({r['module']}). Commands live in dedicated controllers. */\n"
           f"@RestController\n@RequestMapping(\"/api/v1/{r['path']}\")\n"
           f"public class {ent}Controller extends {base} {{\n"
           f"    public {ent}Controller(CrudService crud) {{\n        super(crud, \"{r['path']}\");\n    }}\n}}\n")
    write(f"{JAVA_ROOT}/{ctx}/api/{ent}Controller.java", ctl)

# catalog
lines = []
for r in resources:
    fl = []
    for f in r["fields"]:
        opts = "List.of(" + ", ".join(jstr(o) for o in f["options"]) + ")"
        fl.append(f"                new FieldDef({jstr(f['name'])}, {jstr(f['label'])}, {jstr(f['type'])}, "
                  f"{jstr(f['ref']) if f['ref'] else 'null'}, {opts}, {str(f['required']).lower()}, "
                  f"{str(f['list']).lower()}, {str(f['managed']).lower()}, {str(f['hidden']).lower()}, "
                  f"{str(f['computed']).lower()}, {str(f['guarded']).lower()})")
    roles = "Set.of(" + ", ".join(jstr(x) for x in r["writerRoles"]) + ")"
    lines.append(
        f"        add(new ResourceDef({jstr(r['path'])}, {PKG}.{r['context']}.domain.{r['entity']}.class, "
        f"{jstr(r['context'])}, {jstr(r['module'])}, {jstr(r['label'])}, {jstr(r['singular'])}, "
        f"{jstr(r['prefix']) if r['prefix'] else 'null'}, {jstr(r['display'])}, {str(r['readonly']).lower()}, "
        f"{roles}, List.of(\n" + ",\n".join(fl) + ")));")
catalog = (f"{HEADER}package {PKG}.platform.application;\n\nimport java.util.LinkedHashMap;\nimport java.util.List;\n"
           f"import java.util.Map;\nimport java.util.Set;\n\n/** Resource metadata generated from the model. */\n"
           f"public final class ResourceCatalog {{\n\n    private static final Map<String, ResourceDef> BY_PATH = new LinkedHashMap<>();\n"
           f"    private static final Map<Class<?>, ResourceDef> BY_CLASS = new LinkedHashMap<>();\n\n"
           f"    private ResourceCatalog() {{}}\n\n    private static void add(ResourceDef d) {{\n"
           f"        BY_PATH.put(d.path(), d);\n        BY_CLASS.put(d.entity(), d);\n    }}\n\n"
           f"    public static ResourceDef get(String path) {{\n        return BY_PATH.get(path);\n    }}\n\n"
           f"    public static ResourceDef of(Class<?> type) {{\n        return BY_CLASS.get(type);\n    }}\n\n"
           f"    public static java.util.Collection<ResourceDef> all() {{\n        return BY_PATH.values();\n    }}\n\n"
           f"    static {{\n" + "\n".join(lines) + "\n    }\n}\n")
write(f"{JAVA_ROOT}/platform/application/ResourceCatalog.java", catalog)

# ------------------------------------------------------------------ SQL
ddl = ["-- GENERATED baseline schema (see tools/codegen). Later changes go into new versioned migrations.\n"]
for r in resources:
    cols = ["    id uuid primary key", "    tenant_id uuid not null", "    version bigint not null default 0",
            "    created_at timestamp with time zone not null", "    updated_at timestamp with time zone not null",
            "    created_by varchar(255)"]
    for f in r["fields"]:
        if f["computed"]:
            continue
        cols.append(f"    {snake(f['name'])} {SQL_TYPES[f['type']]}")
    ddl.append(f"create table {r['table']} (\n" + ",\n".join(cols) + "\n);")
    ddl.append(f"create index ix_{r['table']}_tenant on {r['table']} (tenant_id, created_at);")
    for f in r["fields"]:
        if f["ref"] or f["name"] in ("status", "number"):
            ddl.append(f"create index ix_{r['table']}_{snake(f['name'])} on {r['table']} (tenant_id, {snake(f['name'])});")
    if any(f["name"] == "number" for f in r["fields"]):
        ddl.append(f"create unique index ux_{r['table']}_number on {r['table']} (tenant_id, number);")
    ddl.append("")
ddl.append("create unique index ux_pm_occurrence_key on pm_occurrence (tenant_id, plan_id, plan_version, occurrence_key);")
ddl.append("create unique index ux_stock_movement_op on stock_movement (tenant_id, client_operation_id);")
ddl.append("create unique index ux_stock_reservation_op on stock_reservation (tenant_id, client_operation_id);")
ddl.append("create unique index ux_app_user_email on app_user (email);")
ddl.append("create unique index ux_passport_token on passport_token (token);")
write(os.path.join(ROOT, "backend/src/main/resources/db/migration/V1__baseline_schema.sql"), "\n".join(ddl) + "\n")

# ------------------------------------------------------------------ Web registry
web = {
    "modules": {k: {"code": k, "title": v[0], "group": v[1], "icon": v[2]} for k, v in model.MODULES.items()},
    "resources": [
        {k: r[k] for k in ("path", "entity", "context", "module", "label", "singular", "icon", "prefix", "display",
                           "readonly", "writerRoles", "desc")}
        | {"fields": [{k: f[k] for k in ("name", "label", "type", "ref", "options", "required", "list", "managed",
                                         "computed", "guarded")} for f in r["fields"] if not f["hidden"]]}
        for r in resources
    ],
}
write(os.path.join(ROOT, "web/src/generated/registry.json"), json.dumps(web, indent=1) + "\n")

# ------------------------------------------------------------------ OpenAPI
OA_TYPES = {"str": {"type": "string"}, "text": {"type": "string"}, "int": {"type": "integer"},
            "dec": {"type": "number"}, "money": {"type": "number"}, "bool": {"type": "boolean"},
            "date": {"type": "string", "format": "date"}, "datetime": {"type": "string", "format": "date-time"},
            "ref": {"type": "string", "format": "uuid"}}
paths, schemas = {}, {}
err = {"$ref": "#/components/schemas/Problem"}
for r in resources:
    props = {"id": {"type": "string", "format": "uuid", "readOnly": True},
             "version": {"type": "integer", "readOnly": True},
             "createdAt": {"type": "string", "format": "date-time", "readOnly": True},
             "updatedAt": {"type": "string", "format": "date-time", "readOnly": True}}
    for f in r["fields"]:
        if f["hidden"]:
            continue
        p = dict(OA_TYPES.get(f["type"], {"type": "string"}))
        if f["type"] == "enum":
            p = {"type": "string", "enum": f["options"]}
        if f["managed"] or f["computed"] or f["guarded"]:
            p["readOnly"] = True
        p["title"] = f["label"]
        props[f["name"]] = p
    schemas[r["entity"]] = {"type": "object", "properties": props,
                            "required": [f["name"] for f in r["fields"] if f["required"]],
                            "x-owner-context": r["context"], "x-module": r["module"]}
    ref = {"$ref": f"#/components/schemas/{r['entity']}"}
    page = {"type": "object", "properties": {"items": {"type": "array", "items": ref}, "total": {"type": "integer"},
                                             "page": {"type": "integer"}, "size": {"type": "integer"}}}
    tag = model.MODULES[r["module"]][0]
    sec = [{"bearer": []}]
    coll = {"get": {"tags": [tag], "summary": f"List {r['label']}", "security": sec,
                    "parameters": [{"name": n, "in": "query", "schema": {"type": t}} for n, t in
                                   (("q", "string"), ("page", "integer"), ("size", "integer"), ("sort", "string"))],
                    "responses": {"200": {"description": "Page", "content": {"application/json": {"schema": page}}},
                                  "401": {"description": "Unauthenticated"}, "403": {"description": "Forbidden"}},
                    "x-roles-read": "all internal roles", "x-audit": "none"}}
    item = {"get": {"tags": [tag], "summary": f"Get {r['singular']}", "security": sec,
                    "responses": {"200": {"description": "OK", "content": {"application/json": {"schema": ref}}},
                                  "404": {"description": "Not found or not in tenant scope",
                                          "content": {"application/problem+json": {"schema": err}}}}}}
    if not r["readonly"]:
        coll["post"] = {"tags": [tag], "summary": f"Create {r['singular']}", "security": sec,
                        "parameters": [{"name": "Idempotency-Key", "in": "header", "schema": {"type": "string"}}],
                        "requestBody": {"content": {"application/json": {"schema": ref}}},
                        "responses": {"201": {"description": "Created", "content": {"application/json": {"schema": ref}}},
                                      "400": {"description": "Validation", "content": {"application/problem+json": {"schema": err}}},
                                      "403": {"description": "Role not permitted"}},
                        "x-roles-write": r["writerRoles"], "x-audit": "CREATE"}
        item["patch"] = {"tags": [tag], "summary": f"Update {r['singular']}", "security": sec,
                         "parameters": [{"name": "If-Match", "in": "header", "required": True,
                                         "schema": {"type": "string"}, "description": "Current version"}],
                         "requestBody": {"content": {"application/json": {"schema": ref}}},
                         "responses": {"200": {"description": "Updated"},
                                       "412": {"description": "Version precondition failed",
                                               "content": {"application/problem+json": {"schema": err}}}},
                         "x-roles-write": r["writerRoles"], "x-audit": "UPDATE"}
    paths[f"/api/v1/{r['path']}"] = coll
    paths[f"/api/v1/{r['path']}/{{id}}"] = item
    paths[f"/api/v1/{r['path']}/export.csv"] = {"get": {"tags": [tag], "summary": f"Export {r['label']} (CSV)",
                                                        "security": sec, "responses": {"200": {"description": "CSV"}}}}
schemas["Problem"] = {"type": "object", "properties": {k: {"type": "string"} for k in
                                                      ("type", "title", "detail", "code", "correlationId")}
                      | {"status": {"type": "integer"}, "errors": {"type": "array", "items": {"type": "object"}}}}
openapi = {"openapi": "3.1.0", "info": {"title": "OPES Maintain API", "version": "1.0.0",
                                        "description": "Generated resource surface. Lifecycle commands are listed in docs/api/commands.md."},
           "paths": paths,
           "components": {"schemas": schemas, "securitySchemes": {"bearer": {"type": "http", "scheme": "bearer"}}}}
write(os.path.join(ROOT, "contracts/openapi/opes-maintain.openapi.json"), json.dumps(openapi, indent=1) + "\n")

print(f"Generated {len(resources)} resources across {len(model.MODULES)} modules.")
