#!/usr/bin/env python3
"""Generates docs/plan/SCREEN_CATALOG.md: every screen, tab, field and action, derived from the
resource model, the web action catalog and the custom pages. Run after changing the model or UI."""
import json, os, re
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
reg = json.load(open(os.path.join(ROOT, "web/src/generated/registry.json")))
actions_src = open(os.path.join(ROOT, "web/src/lib/actions.ts")).read()
detail_src = open(os.path.join(ROOT, "web/src/components/ResourceDetail.tsx")).read()

def actions_for(path):
    m = re.search(r'\n  "?%s"?: \[(.*?)\n  \],' % re.escape(path), actions_src, re.S)
    if not m: return []
    return re.findall(r'key: "[^"]+", label: "([^"]+)"', m.group(1))

PRINT = dict(re.findall(r'"?([a-z-]+)"?: "([a-z-]+)",', actions_src.split("PRINTABLE")[1]))
CUSTOM_TABS = {
    "work-orders": ["Execution & cost (task checklist, parts reserve/issue/release, labor log, live job cost)"],
    "assets": ["QR passport (QR code, scans, open/print)", "Hierarchy (component tree)"],
    "pm-plans": ["Forecast (next 8 occurrences in site-local time and UTC)"],
    "parts": ["Stock by warehouse (+ receive, adjust, transfer, return)"],
    "warehouses": ["Stock on hand"],
    "documents": ["File (upload, replace, download, checksum, scan status)"],
}
DOC_TABS = {"assets", "customers", "sites", "work-orders"}
labels = {r["path"]: r["label"] for r in reg["resources"]}
related = {}
for r in reg["resources"]:
    for f in r["fields"]:
        if f["ref"] and r["path"] not in ("audit-events", "outbox-events"):
            related.setdefault(f["ref"], []).append((r["label"], f))
for k, v in related.items():
    names = [x[0] for x in v]
    related[k] = [(f"{n} (children)") if f["name"] in ("parentId", "parentWorkOrderId") else (f"{n} ({f['label'].lower()})" if names.count(n) > 1 else n) for n, f in v]

out = ["# Screen catalog (generated)", "",
       "Generated by `tools/codegen/catalog.py` from the live model and UI code. Do not edit by hand.", "",
       f"**{len(reg['modules'])} modules · {len(reg['resources'])} resources · {len(reg['resources'])*4} generic screens (list, detail, new, edit) + 24 workflow screens**", ""]
out += ["## Workflow screens", "",
"| Route | Screen | Contents | Roles |", "|---|---|---|---|",
"| `/login` | Sign in | Email/password, demo role shortcuts, OIDC when configured | public |",
"| `/` | Dashboard | 8 KPI tiles, created-vs-completed chart, open work by priority/type, open work by due date, recommendations, low stock | internal |",
"| `/work-board` | Work board | 9 lifecycle lanes, site and type filters, cards with priority, asset, assignee, due, SLA breach | internal |",
"| `/dispatch` | Dispatch calendar | Week grid of technicians × days, assignment events, awaiting-assignment list, new assignment | dispatcher, planner, manager |",
"| `/pm-board` | PM board | Plan lanes by lifecycle, next due or meter threshold, recent occurrences | planner, manager |",
"| `/stock` | Stock control | Inventory KPIs, stock movement by part, warehouse stock, reorder list, open reservations, latest movements | storekeeper, manager |",
"| `/analytics` | Analytics | PM compliance, availability, planned ratio, SLA breach rings, MTTR/MTBF/downtime, trend, status, downtime by asset, cost by site; site and period filters | internal |",
"| `/reports` | Reports | 8 management reports + 8 record documents | internal |",
"| `/reports/[type]` | Report view | Date range, printable table, CSV, print/PDF | internal |",
"| `/print/[kind]/[id]` | Documents | Work order report, asset passport/history, quotation, permit, purchase order, calibration certificate, inspection record, billing statement | per record |",
"| `/technician` | Technician queue | Sync bar, assigned jobs, permit warnings, report fault, scan | technician |",
"| `/technician/[id]` | Job | Safety briefing, start/complete, labor timer, checklist, meter reading, photo evidence, offline queue | technician |",
"| `/scan` | QR scanner | Camera scan with manual code entry | internal |",
"| `/passport/[token]` | Equipment passport | Status, safety, location, warranty, history, documents, report fault | authenticated |",
"| `/portal` | Customer portal | Equipment, requests, active jobs, sign-off, quotes, recent jobs | customer |",
"| `/modules` | Module catalog | All 28 modules with links | internal |",
"| `/settings` | Settings | Profile, language, password, organization, administration links | all |",
"| `/notifications` | Notifications | Role and personal notifications, mark read | all |",
""]
groups = {}
for code, m in reg["modules"].items():
    groups.setdefault(m["group"], []).append((code, m))
for g, mods in groups.items():
    out += [f"## {g}", ""]
    for code, m in sorted(mods):
        out += [f"### {code} — {m['title']}", ""]
        for r in [x for x in reg["resources"] if x["module"] == code]:
            p = r["path"]
            tabs = ["Details"] + CUSTOM_TABS.get(p, []) + (["Documents"] if p in DOC_TABS else []) + related.get(p, []) + ["History (managers, auditors)"]
            acts = actions_for(p)
            wf = "Work-order transitions from server (Triage → Approve → Plan → Dispatch → Start → Complete → Review → Close; Hold, Resume, Cancel, Reopen)" if p == "work-orders" else ", ".join(acts) or "—"
            out += [f"#### {r['label']} — `/m/{p}`", "", r["desc"], "",
                    f"- **Screens:** list (search, {', '.join(f['label'] for f in r['fields'] if f['type']=='enum' and f['list'])[:120] or 'no'} filters, sort, pagination, CSV)" + ("" if r["readonly"] else ", new, edit") + ", detail",
                    f"- **Columns:** {', '.join(f['label'] for f in r['fields'] if f['list'])}",
                    f"- **Form fields:** {', '.join(f['label'] + ('*' if f['required'] else '') for f in r['fields'] if not f['managed'] and not f['computed']) if not r['readonly'] else 'read-only — created by domain commands'}",
                    f"- **Detail tabs:** {', '.join(tabs)}",
                    f"- **Actions:** {wf}",
                    f"- **Printable:** {'yes — /print/' + PRINT[p] if p in PRINT else 'no'}",
                    f"- **Write roles:** {', '.join(r['writerRoles'])}", ""]
open(os.path.join(ROOT, "docs/plan/SCREEN_CATALOG.md"), "w").write("\n".join(out) + "\n")
print("screen catalog written", len(out), "lines")
